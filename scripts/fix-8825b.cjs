/**
 * יישור 88.25 לכלל שעדי קבע: **מוסיפים, לא מחליפים.**
 *
 * כשהגרסה הישנה והמקור האנגלי חלוקים, שתי ההתוויות נשמרות - אלא אם
 * אחת מהן שגויה ממש. הסבב הקודם החליף בשני מקומות במקום להוסיף.
 */
const fs = require('fs')
const p = 'src/data/zones/zone88.ts'
let s = fs.readFileSync(p, 'utf8')

const FIXES = [
  // המקור: insomnia and palpitations. הישן אמר נוירסתניה. שתיהן נשמרות.
  ['לטיפול בנדודי שינה ובדפיקות לב', 'לטיפול בנדודי שינה, בדפיקות לב ובנוירסתניה'],
  // המקור מונה dizziness, הישן אמר שבץ. שתיהן נשמרות.
  [
    'כגון שיתוק פנים, סחרחורת והמיפלגיה (משבץ רוח)',
    'כגון שיתוק פנים, סחרחורת, שבץ והמיפלגיה (משבץ רוח)',
  ],
  // "דורבנות" הוא תרגום לגיטימי של osteophytes - נשמר לצד המונח הרשמי
  ['אוסטאופיטים בעמוד השדרה', 'אוסטאופיטים (דורבנות) בעמוד השדרה'],
  // עדי ביקש את הניסוח "הנקודה מטפלת ב"
  ['ולכן הנקודה יכולה לטפל בכאב', 'ולכן הנקודה מטפלת בכאב'],
]

let n = 0
for (const [from, to] of FIXES) {
  if (!s.includes(from)) { console.error('✗ לא נמצא: ' + from.slice(0, 45)); continue }
  s = s.replace(from, to)
  n++
}
fs.writeFileSync(p, s)
console.log(n + '/' + FIXES.length + ' תיקונים הוחלו')
